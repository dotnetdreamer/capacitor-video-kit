/**
 * Case-insensitive substring search over the names, in catalogue order. An empty query returns
 * nothing rather than everything: the sheet shows the grouped grid when the field is empty, and a
 * flat list of all ~270 would just repeat it without headings.
 */
export function searchEmoji(query: string): EmojiItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return EMOJI_GROUPS.flatMap((g) => g.items).filter((item) => item.name.includes(q));
}
