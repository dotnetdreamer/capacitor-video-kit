/**
 * The "Emoji" tab of the Stickers sheet: a curated catalogue for food and place reviews rather than
 * the full Unicode list, which would bury the handful people actually use under flags and office
 * supplies.
 *
 * An emoji layer is drawn with the device's own emoji font (`StickerOverlay.emoji`), so the list is
 * limited to what Android 10's Noto Color Emoji carries - Emoji 12.0 and older, with no ZWJ
 * sequences. Anything newer (bubble tea, pinched fingers, the melting face...) would show as an
 * empty box on those phones, both in the picker and burned into the posted video. Each entry was
 * checked against the cmap of the font pulled from an Android 10 device. Characters whose default
 * presentation is text (a heart, the sun, an arrow) carry U+FE0F so they draw in colour.
 */

